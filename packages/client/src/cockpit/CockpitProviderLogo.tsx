/** Which provider a Cockpit list row shows a logo for. */
export type CockpitProviderBrand = "claude" | "openai";

export function cockpitProviderBrand(
  provider: string | undefined,
): CockpitProviderBrand | null {
  if (provider === "codex") return "openai";
  // Older sessions without a provider are Claude's (DEFAULT_PROVIDER).
  if (!provider || provider.startsWith("claude")) return "claude";
  return null;
}

export function cockpitProviderBrandName(brand: CockpitProviderBrand): string {
  return brand === "claude" ? "Claude" : "Codex";
}

