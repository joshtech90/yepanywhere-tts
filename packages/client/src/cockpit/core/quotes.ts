/** A random quote index, never the one just shown when there is a choice. */
export function pickCockpitQuote(
  current: number | null,
  random: () => number = Math.random,
  count: number = COCKPIT_QUOTES.length,
): number {
  if (count <= 1) return 0;
  if (current === null || current < 0 || current >= count) {
    return Math.min(count - 1, Math.floor(random() * count));
  }
  // Draw from the others, then step over the current index.
  const other = Math.min(count - 2, Math.floor(random() * (count - 1)));
  return other >= current ? other + 1 : other;
}
