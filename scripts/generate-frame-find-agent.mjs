/**
 * Bundle the artifact-frame find agent into a committed script string.
 *
 * The artifact server appends this script to HTML it serves into a YA viewer
 * frame. It is generated from packages/shared/src/find/frameFindAgent.ts, the
 * same find engine YA's own viewers import, so the two cannot drift apart.
 * A runtime `Function.toString()` would not do: the dev server's TypeScript
 * loader inserts `__name(...)` helper calls that do not exist in the frame.
 *
 *   node scripts/generate-frame-find-agent.mjs          # rewrite the file
 *   node scripts/generate-frame-find-agent.mjs --check  # fail if stale
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const findDir = join(root, "packages/shared/src/find");
const entry = join(findDir, "frameFindAgent.ts");
const output = join(findDir, "frameFindAgent.generated.ts");

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  minify: true,
  target: "es2020",
  legalComments: "none",
  write: false,
});
// The script is inlined in HTML, where "</script" would end it early.
const script = result.outputFiles[0].text
  .trim()
  .replace(/<\/script/gi, "<\\/script");
// Committed exactly as the repository formatter prints it, so `format:check`
// and this script's `--check` agree about the same bytes.
const source = execFileSync(
  process.execPath,
  [join(root, "scripts/biome.cjs"), "format", `--stdin-file-path=${output}`],
  {
    input: `// biome-ignore-all lint/suspicious/noTemplateCurlyInString: the string is minified JavaScript, whose template literals are meant to be text here.
// Generated by scripts/generate-frame-find-agent.mjs from frameFindAgent.ts.
// Do not edit; run \`pnpm find-agent:generate\` after changing the find sources.
export const FRAME_FIND_AGENT_SCRIPT = ${JSON.stringify(script)};
`,
    encoding: "utf-8",
    cwd: root,
  },
);

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(output, "utf-8");
  } catch {}
  if (current !== source) {
    console.error(
      "frameFindAgent.generated.ts is stale; run `pnpm find-agent:generate`.",
    );
    process.exit(1);
  }
  console.log("Frame find agent script is up to date.");
} else {
  writeFileSync(output, source);
  console.log(`Wrote ${output} (${script.length} characters).`);
}
